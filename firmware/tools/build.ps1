# ============================================================
#  一行编译 / 烧录 / OTA
#  用法（推荐用 tools\build.cmd 调用，避免 PowerShell 执行策略限制）：
#    tools\build.cmd                      只编译
#    tools\build.cmd -Upload COM5         串口烧录（需 IO0 接地）
#    tools\build.cmd -Upload 192.168.1.23 OTA 升级（不需要 IO0）
#    tools\build.cmd -Upload COM5 -Monitor COM5
#    tools\build.cmd -Clean
#    tools\build.cmd -Export arduino\esp32clock   导出给 Arduino IDE
# ============================================================
param(
  [string] $Upload  = "",
  [string] $Monitor = "",
  [string] $ArduinoCli = "",
  [string] $Fqbn = "esp32:esp32:esp32cam",
  [string] $BoardOptions = "PartitionScheme=min_spiffs",
  [string] $Export = "",
  [switch] $Clean
)

$ErrorActionPreference = 'Stop'
$root   = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$build  = Join-Path $root ".build"
$sketch = Join-Path $build "esp32clock"
$outDir = Join-Path $build "out"

function Find-Cli {
  param([string] $hint)
  if ($hint) { if (Test-Path $hint) { return $hint } else { throw "找不到 arduino-cli: $hint" } }
  $candidates = @(
    (Join-Path $env:USERPROFILE "arduino-cli\arduino-cli.exe"),
    "arduino-cli.exe"
  )
  foreach ($c in $candidates) {
    $cmd = Get-Command $c -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
  }
  throw "找不到 arduino-cli，请用 -ArduinoCli 指定路径"
}

$cli = Find-Cli $ArduinoCli
Write-Host "== arduino-cli: $cli" -ForegroundColor Cyan
Write-Host "== 工程: $root" -ForegroundColor Cyan

if ($Clean) { Remove-Item $build -Recurse -Force -ErrorAction SilentlyContinue }
New-Item -ItemType Directory -Force -Path $sketch, $outDir | Out-Null
Get-ChildItem $sketch -File -ErrorAction SilentlyContinue | Remove-Item -Force

Copy-Item (Join-Path $root "src\*.cpp")   $sketch -Force
Copy-Item (Join-Path $root "src\*.h")     $sketch -Force
Copy-Item (Join-Path $root "include\*.h") $sketch -Force

# .ino 必须是 UTF-8 无 BOM
$ino = Join-Path $sketch "esp32clock.ino"
[IO.File]::WriteAllText($ino,
  "// generated by tools/build.ps1 - real setup()/loop() live in main.cpp`n" +
  "// Arduino IDE: AI Thinker ESP32-CAM + Minimal SPIFFS (1.9MB APP with OTA)`n",
  (New-Object System.Text.UTF8Encoding($false)))

Write-Host "== 编译 ($Fqbn / $BoardOptions)" -ForegroundColor Cyan
& $cli compile --fqbn $Fqbn --board-options $BoardOptions --output-dir $outDir --warnings default $sketch
if ($LASTEXITCODE -ne 0) { throw "编译失败（exit $LASTEXITCODE）" }

$bin = Get-ChildItem $outDir -Filter "*.ino.bin" | Select-Object -First 1
if ($bin) {
  Write-Host ("== 固件: {0}  ({1:N0} KB)" -f $bin.FullName, ($bin.Length / 1KB)) -ForegroundColor Green
}

if ($Export) {
  $dst = if ([IO.Path]::IsPathRooted($Export)) { $Export } else { Join-Path $root $Export }
  New-Item -ItemType Directory -Force -Path $dst | Out-Null
  Get-ChildItem $dst -File -ErrorAction SilentlyContinue | Remove-Item -Force
  Copy-Item (Join-Path $root "src\*.cpp")   $dst -Force
  Copy-Item (Join-Path $root "src\*.h")     $dst -Force
  Copy-Item (Join-Path $root "include\*.h") $dst -Force
  [IO.File]::WriteAllText((Join-Path $dst "esp32clock.ino"),
    "// generated by tools/build.ps1 -Export`n" +
    "// Arduino IDE: AI Thinker ESP32-CAM + Minimal SPIFFS (1.9MB APP with OTA)`n",
    (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "== 已导出 Arduino sketch: $dst" -ForegroundColor Green
}

if ($Upload) {
  $isOta = ($Upload -match '^\d{1,3}(\.\d{1,3}){3}$') -or ($Upload -match '\.local$')
  if ($isOta) {
    # ArduinoOTA 走 UDP 3232，用 esp32 核心自带的 espota.py
    $hostIp = $Upload
    if ($hostIp -match '\.local$') {
      try { $hostIp = (Resolve-DnsName $hostIp -ErrorAction Stop | Select-Object -First 1).IPAddress }
      catch { throw "解析不到 $Upload，请直接用 IP（例如 192.168.1.23）" }
    }
    $coreDir = Get-ChildItem (Join-Path $env:LOCALAPPDATA "Arduino15\packages\esp32\hardware\esp32") -Directory -ErrorAction SilentlyContinue |
               Sort-Object Name -Descending | Select-Object -First 1
    if (-not $coreDir) { throw "找不到 esp32 核心目录" }
    $espota = Join-Path $coreDir.FullName "tools\espota.py"

    $py = @(
      (Join-Path $env:USERPROFILE ".pio-venv\Scripts\python.exe"),
      "C:\Python312\python.exe"
    ) | Where-Object { Test-Path $_ } | Select-Object -First 1
    if (-not $py) {
      $c = Get-Command python -ErrorAction SilentlyContinue
      if ($c) { $py = $c.Source } else { throw "找不到 python（espota.py 需要）" }
    }

    Write-Host "== OTA 升级到 $hostIp（UDP 3232，不需要 IO0）" -ForegroundColor Cyan
    & $py $espota -i $hostIp -p 3232 -f $bin.FullName
    if ($LASTEXITCODE -ne 0) { Write-Host "== OTA 返回 $LASTEXITCODE（espota 有时在成功后仍返回非 0，看上面是否 100% Done）" -ForegroundColor Yellow }
  } else {
    Write-Host "== 串口烧录到 $Upload（需要 IO0 接地）" -ForegroundColor Cyan
    & $cli upload -p $Upload --fqbn $Fqbn --board-options $BoardOptions --input-dir $outDir
    if ($LASTEXITCODE -ne 0) { throw "上传失败（exit $LASTEXITCODE）" }
  }
  Write-Host "== 上传完成" -ForegroundColor Green
}

if ($Monitor) {
  Write-Host "== 打开串口 $Monitor（Ctrl+C 退出）" -ForegroundColor Cyan
  & $cli monitor -p $Monitor -c baudrate=115200
}

exit 0
